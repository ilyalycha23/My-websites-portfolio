  window.ERAPT_getProductPreviewSrc = function (p) {
    if (p.colorVariants && p.colorVariants.length > 0) {
      var first = p.colorVariants[0];
      if (first.images && first.images.length > 0) return first.images[0];
    }
    if (p.images && p.images.length > 0) return p.images[0];
    return "";
  };

  /**
   * Набор картинок и подпись для выбранного цвета (или единственного варианта).
   * colorId — значение из URL ?color= или id варианта из colorVariants.
   */
  window.ERAPT_resolveColorVariant = function (p, colorId) {
    if (p.colorVariants && p.colorVariants.length > 0) {
      var found = p.colorVariants.find(function (v) {
        return v.id === colorId;
      });
      var v = found || p.colorVariants[0];
      return {
        id: v.id,
        label: v.label,
        images: v.images && v.images.length ? v.images : [],
      };
    }
    return {
      id: null,
      label: null,
      images: p.images && p.images.length ? p.images : [],
    };
  };
